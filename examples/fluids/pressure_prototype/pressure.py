"""Experimental velocity-only pressure projection for specialized analytic samplers.

Closed: analytic box or sphere. Exterior: analytic sphere or torus, with a
pseudo-boundary box. These are application estimators, not generic surface
solvers. Sampling distributions and inverse-probability weights are owned by
this prototype; ordinary integration/refill is reused from sphereWalker.
"""
from typing import NamedTuple

import jax
import jax.numpy as jnp
import numpy as np

from sphereWalker.types import WalkerDiagnostics


class ProjectionResult(NamedTuple):
    velocity: jax.Array
    pressure_gradient: jax.Array
    diagnostics: WalkerDiagnostics


class ClosedPressureProjector:
    """Single-path boundary samples generated by the shared MC integrator.

    n_samples counts shared boundary walks, not independent walks per query.
    Each walk stores length+1 hits; no branching or all-hit path tree exists.
    """
    @staticmethod
    def _make_integrator(geometry, velocity, **options):
        from examples.fluids.pressure_prototype.boundary_integrator import WoBPressureIntegrator
        return WoBPressureIntegrator(geometry, velocity, **options)

    def __init__(self, geometry, velocity, *, query_batch_size=64, **options):
        from utils.batch_driver import validate_max_active_states
        self.query_batch_size = validate_max_active_states(query_batch_size)
        self.velocity = velocity
        self.geometry = geometry
        self.gradient_solver = self._make_integrator(geometry, velocity, **options)
        gather_jax = self._gather_reference
        self._gather_jax = jax.jit(gather_jax,
            # Avoid autotuner validation buffers for the sample-reduction loop.
            compiler_options={'xla_gpu_autotune_level': 0})
        self._gather = jax.jit(lambda p, x, s: jax.lax.platform_dependent(
            p, x, s, cuda=self._gather_cuda, default=gather_jax))
        self._gather_walks = jax.jit(self._gather_walk_records,
                                    static_argnames=('n_walks',))
        direct_jax = lambda p, x, k: jax.lax.map(
            lambda pair: self._direct_point(p, pair[0], pair[1]),
            (x, k), batch_size=self.query_batch_size)
        self._direct_jax = jax.jit(direct_jax)
        self._prepare_gather = jax.jit(self._gather_records)
        from examples.fluids.grid import GridVelocity
        if isinstance(velocity, GridVelocity):
            self._direct = jax.jit(lambda p, x, k: jax.lax.platform_dependent(
                p, x, k, cuda=self._direct_cuda, default=direct_jax))
        else:
            self._direct = self._direct_jax

    def _direct_point(self, params, point, key):
        return self.gradient_solver._source(params, point, key, direct=True)

    def _gather_records(self, params, samples, key, n_samples):
        return samples

    def _direct_cuda(self, params, points, keys):
        from examples.fluids.pressure_prototype.warp_direct import grid_source
        return grid_source(self.gradient_solver, self.velocity, params, points,
                           keys, self.query_batch_size)

    def _gather_cuda(self, params, points, samples):
        from examples.fluids.pressure_prototype.warp_gather import boundary_gather
        velocities = jax.vmap(self.velocity, (None, 0))(params, points)
        return boundary_gather(points, velocities, samples,
                               self.gradient_solver.regularization)

    def _gather_reference(self, params, points, samples):
        return jax.lax.map(lambda point: self._gather_point(params, point, samples),
                           points, batch_size=self.query_batch_size)

    def _gather_walk_records(self, params, points, samples, *, n_walks):
        """Use the known walk layout only for production projection records."""
        records_per_walk = self.gradient_solver.path_length+1
        walk_count = n_walks*records_per_walk
        if len(samples) < walk_count:
            raise ValueError('projection cache is shorter than its walk layout')

        def cuda(params, points, samples):
            if records_per_walk-1 > 128:
                return self._gather_cuda(params, points, samples)
            from examples.fluids.pressure_prototype.warp_gather import boundary_gather_split
            walks = samples[:walk_count].reshape(n_walks, records_per_walk, 7)
            affine = jnp.concatenate((walks[:, 0], samples[walk_count:]), axis=0)
            scalar = walks[:, 1:, :4].reshape(-1, 4)
            velocities = jax.vmap(self.velocity, (None, 0))(params, points)
            return boundary_gather_split(points, velocities, affine, scalar,
                                         self.gradient_solver.regularization,
                                         continuations_per_root=records_per_walk-1)

        return jax.lax.platform_dependent(params, points, samples,
                                          cuda=cuda, default=self._gather_reference)

    def _gather_point(self, params, x, samples):
        u = self.velocity(params, x)
        # Bound the query-by-sample workspace; scan carries only one vector.
        block_size = 4096
        blocks = jnp.pad(samples, ((0, -len(samples) % block_size), (0, 0)))
        def accumulate(total, block):
            green = jax.vmap(lambda y: self.gradient_solver._green(x, y))(block[:, :3])
            weights = block[:, 3]+jnp.sum(block[:, 4:]*u, axis=-1)
            return total+jnp.sum(green*weights[:, None], axis=0), None
        return jax.lax.scan(accumulate, jnp.zeros(3, x.dtype),
                            blocks.reshape(-1, block_size, 7))[0]

    def project(self, params, points, key, *, n_samples, **options):
        if not bool(jnp.all(jax.vmap(self.geometry.contains)(points))):
            raise ValueError('projection points must lie inside the fluid')
        kb, kv = jax.random.split(key)
        roots = jnp.zeros((n_samples, 3), points.dtype)
        details = self.gradient_solver.integrate_batch(
            params, roots, kb, init_trust_region_size=1., n_samples=1,
            return_details=True, **options)
        if not bool(jnp.all(details.complete & (details.successful_samples == 1))):
            raise RuntimeError(f'incomplete pressure walks: {np.asarray(details.termination_counts).sum(0).tolist()}')
        samples = self._prepare_gather(
            params, details.contribution_sum.reshape((-1, 7)), key, n_samples)
        boundary = self._gather_walks(params, points, samples, n_walks=n_samples)/n_samples
        keys = jax.random.split(kv, len(points))
        volume = self._direct(params, points, keys)
        gradient = boundary-volume
        velocity = jax.vmap(self.velocity, (None, 0))(params, points)-gradient
        if not bool(jnp.all(jnp.isfinite(velocity))):
            raise RuntimeError('nonfinite projected velocity')
        return ProjectionResult(velocity, gradient, details)


class ExteriorPressureProjector(ClosedPressureProjector):
    """Unbounded projection with fresh shared pseudo-boundary sources.

    Pseudo sources join the walk records, including their negative sign in
    the pressure gradient. Sharing changes spatial covariance, not the
    pointwise expectation. Boundary-root source estimates stay unchanged.
    """
    @staticmethod
    def _make_integrator(geometry, velocity, **options):
        from examples.fluids.pressure_prototype.boundary_integrator import ExteriorWoBPressureIntegrator
        return ExteriorWoBPressureIntegrator(geometry, velocity, **options)

    def _direct_point(self, params, point, key):
        # Preserve the original per-target volume draws when removing pseudo.
        volume_key, _ = jax.random.split(key)
        return self.gradient_solver._volume(
            params, point, volume_key, self.gradient_solver.volume_samples)

    def _direct_cuda(self, params, points, keys):
        from examples.fluids.pressure_prototype.warp_direct import grid_source
        return grid_source(self.gradient_solver, self.velocity, params, points,
                           keys, self.query_batch_size, include_pseudo=False)

    def _gather_records(self, params, samples, key, n_samples):
        # Domain-separate from both the walk key and per-target volume keys.
        pseudo_key = jax.random.fold_in(key, 0x50534555)
        pseudo = self.gradient_solver.pseudo_records(params, pseudo_key, samples.dtype)
        # project divides the entire gather by the number of boundary walks:
        # B/W - V - P = (B - W/M * sum(pseudo records))/W - V.
        scale = jnp.asarray(n_samples, samples.dtype)/self.gradient_solver.pseudo_samples
        pseudo = pseudo.at[:, 3:].multiply(-scale)
        return jnp.concatenate((samples, pseudo), axis=0)
